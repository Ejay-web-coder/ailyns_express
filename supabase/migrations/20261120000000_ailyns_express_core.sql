-- Ailyn's Express core schema: roles (customer / rider / admin), products,
-- orders with rider assignment, an order event timeline, and live rider location.
-- Every order write goes through a SECURITY DEFINER function so prices, stock and
-- status transitions are enforced in the database, not in the browser.

create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------- types
create type public.app_role as enum ('customer', 'rider', 'admin');
create type public.order_status as enum (
  'pending', 'confirmed', 'preparing', 'ready', 'out_for_delivery', 'delivered', 'cancelled'
);

-- ---------------------------------------------------------------- tables
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role public.app_role not null default 'customer',
  full_name text not null default '',
  email text,
  phone text,
  avatar_url text,
  vehicle text,
  plate_number text,
  rider_approved boolean not null default false,
  rider_online boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  type text not null check (type in ('food', 'grocery')),
  price numeric(10, 2) not null check (price >= 0),
  rating numeric(2, 1) not null default 4.5,
  image text not null default '',
  description text not null default '',
  ingredients text,
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create sequence public.order_code_seq start 240520;

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  code text not null unique default ('AE-' || nextval('public.order_code_seq')::text),
  customer_id uuid not null references public.profiles (id) on delete cascade,
  rider_id uuid references public.profiles (id) on delete set null,
  status public.order_status not null default 'pending',
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  address text not null,
  city text not null,
  province text not null,
  notes text,
  payment_method text not null check (payment_method in ('cod', 'gcash')),
  subtotal numeric(10, 2) not null,
  delivery_fee numeric(10, 2) not null,
  discount numeric(10, 2) not null default 0,
  total numeric(10, 2) not null,
  rider_lat double precision,
  rider_lng double precision,
  rider_location_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index orders_customer_idx on public.orders (customer_id, created_at desc);
create index orders_rider_idx on public.orders (rider_id, created_at desc);
create index orders_status_idx on public.orders (status);

create table public.order_items (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  product_id bigint references public.products (id) on delete set null,
  name text not null,
  image text not null default '',
  price numeric(10, 2) not null,
  quantity integer not null check (quantity > 0)
);
create index order_items_order_idx on public.order_items (order_id);
create index order_items_product_idx on public.order_items (product_id);

create table public.order_events (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  status public.order_status not null,
  note text,
  actor_id uuid references public.profiles (id) on delete set null,
  actor_role public.app_role,
  created_at timestamptz not null default now()
);
create index order_events_order_idx on public.order_events (order_id, created_at);
create index order_events_actor_idx on public.order_events (actor_id);

-- ---------------------------------------------------------------- helpers
create or replace function public.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;

create trigger profiles_touch before update on public.profiles
  for each row execute function public.touch_updated_at();
create trigger orders_touch before update on public.orders
  for each row execute function public.touch_updated_at();

create or replace function public.my_role()
returns public.app_role language sql stable security definer set search_path = '' as $$
  select role from public.profiles where id = (select auth.uid())
$$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where id = (select auth.uid()) and role = 'admin')
$$;

create or replace function public.is_approved_rider()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'rider' and rider_approved
  )
$$;

-- A customer may see the profile of a rider assigned to one of their orders.
create or replace function public.is_my_rider(p_rider uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.orders
    where rider_id = p_rider and customer_id = (select auth.uid())
  )
$$;

-- New auth user -> profile. Self sign-up can only ever produce customer or rider;
-- admins are promoted manually (see README).
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
begin
  insert into public.profiles (id, role, full_name, email, phone, avatar_url, vehicle, plate_number)
  values (
    new.id,
    case when meta ->> 'role' = 'rider' then 'rider'::public.app_role else 'customer'::public.app_role end,
    coalesce(nullif(meta ->> 'full_name', ''), nullif(meta ->> 'name', ''), split_part(coalesce(new.email, ''), '@', 1)),
    new.email,
    nullif(meta ->> 'phone', ''),
    coalesce(meta ->> 'avatar_url', meta ->> 'picture'),
    nullif(meta ->> 'vehicle', ''),
    nullif(meta ->> 'plate_number', '')
  );
  return new;
end $$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.log_order_event(p_order uuid, p_status public.order_status, p_note text)
returns void language sql security definer set search_path = '' as $$
  insert into public.order_events (order_id, status, note, actor_id, actor_role)
  values (p_order, p_status, p_note, (select auth.uid()), public.my_role());
$$;

create or replace function public.restore_order_stock(p_order uuid)
returns void language sql security definer set search_path = '' as $$
  update public.products p
     set stock = p.stock + i.quantity
    from public.order_items i
   where i.order_id = p_order and i.product_id = p.id;
$$;

-- ---------------------------------------------------------------- RLS
alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.order_events enable row level security;

create policy "profiles: read own, admin, or my rider" on public.profiles
  for select to authenticated
  using (
    id = (select auth.uid())
    or (select public.is_admin())
    or (role = 'rider' and public.is_my_rider(id))
  );

create policy "profiles: update own" on public.profiles
  for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- Users may only edit harmless columns; role / approval go through admin functions.
revoke update on public.profiles from anon, authenticated;
grant update (full_name, phone, avatar_url, vehicle, plate_number, rider_online)
  on public.profiles to authenticated;

create policy "products: public catalog" on public.products
  for select to anon
  using (active);
create policy "products: signed-in catalog" on public.products
  for select to authenticated
  using (active or (select public.is_admin()));
create policy "products: admin insert" on public.products
  for insert to authenticated with check ((select public.is_admin()));
create policy "products: admin update" on public.products
  for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "products: admin delete" on public.products
  for delete to authenticated using ((select public.is_admin()));

create policy "orders: customer, assigned rider, open jobs, admin" on public.orders
  for select to authenticated
  using (
    customer_id = (select auth.uid())
    or rider_id = (select auth.uid())
    or (select public.is_admin())
    or (
      rider_id is null
      and status in ('confirmed', 'preparing', 'ready')
      and (select public.is_approved_rider())
    )
  );

create policy "order_items: visible with order" on public.order_items
  for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id));

create policy "order_events: visible with order" on public.order_events
  for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id));

-- No direct writes to orders / items / events: everything goes through the functions below.
revoke insert, update, delete on public.orders, public.order_items, public.order_events
  from anon, authenticated;

-- ---------------------------------------------------------------- customer API
create or replace function public.place_order(
  p_items jsonb,
  p_name text,
  p_phone text,
  p_email text,
  p_address text,
  p_city text,
  p_province text,
  p_notes text,
  p_payment text
) returns public.orders
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_order public.orders;
  v_item jsonb;
  v_product public.products;
  v_qty integer;
  v_subtotal numeric(10, 2) := 0;
  v_fee numeric(10, 2) := 49;
  v_discount numeric(10, 2) := 0;
begin
  if v_uid is null then raise exception 'Please sign in to place an order'; end if;
  if public.my_role() is distinct from 'customer' then
    raise exception 'Only customer accounts can place orders';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Your cart is empty';
  end if;
  if coalesce(trim(p_name), '') = '' or coalesce(trim(p_phone), '') = ''
     or coalesce(trim(p_address), '') = '' or coalesce(trim(p_city), '') = '' then
    raise exception 'Name, phone, address and city are required';
  end if;
  if p_payment not in ('cod', 'gcash') then raise exception 'Unknown payment method'; end if;

  -- First order (ignoring cancelled ones) gets the ₱30 welcome discount.
  if not exists (
    select 1 from public.orders where customer_id = v_uid and status <> 'cancelled'
  ) then
    v_discount := 30;
  end if;

  insert into public.orders (
    customer_id, customer_name, customer_phone, customer_email, address, city, province,
    notes, payment_method, subtotal, delivery_fee, discount, total
  ) values (
    v_uid, trim(p_name), trim(p_phone), nullif(trim(p_email), ''), trim(p_address), trim(p_city),
    coalesce(trim(p_province), ''), nullif(trim(p_notes), ''), p_payment, 0, v_fee, v_discount, 0
  ) returning * into v_order;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item ->> 'quantity')::integer;
    if v_qty is null or v_qty < 1 or v_qty > 99 then raise exception 'Invalid quantity'; end if;

    select * into v_product from public.products
     where id = (v_item ->> 'product_id')::bigint and active
     for update;
    if not found then raise exception 'A product in your cart is no longer available'; end if;
    if v_product.stock < v_qty then
      raise exception 'Only % left of %', v_product.stock, v_product.name;
    end if;

    update public.products set stock = stock - v_qty where id = v_product.id;
    insert into public.order_items (order_id, product_id, name, image, price, quantity)
    values (v_order.id, v_product.id, v_product.name, v_product.image, v_product.price, v_qty);
    v_subtotal := v_subtotal + v_product.price * v_qty;
  end loop;

  update public.orders
     set subtotal = v_subtotal,
         total = greatest(0, v_subtotal + v_fee - v_discount)
   where id = v_order.id
  returning * into v_order;

  perform public.log_order_event(v_order.id, 'pending', 'Order placed');
  return v_order;
end $$;

create or replace function public.customer_cancel_order(p_order uuid)
returns void language plpgsql security definer set search_path = '' as $$
begin
  update public.orders set status = 'cancelled'
   where id = p_order and customer_id = auth.uid() and status = 'pending';
  if not found then raise exception 'This order can no longer be cancelled'; end if;
  perform public.restore_order_stock(p_order);
  perform public.log_order_event(p_order, 'cancelled', 'Cancelled by customer');
end $$;

-- OAuth sign-ups cannot carry a role, so a fresh account opened from the rider
-- portal converts itself here. Only an account with no orders may convert.
create or replace function public.become_rider(
  p_full_name text default null,
  p_phone text default null,
  p_vehicle text default null,
  p_plate text default null
) returns void language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := auth.uid();
  v_role public.app_role := public.my_role();
begin
  if v_uid is null then raise exception 'Not signed in'; end if;
  if v_role = 'admin' then raise exception 'Admin accounts cannot become riders'; end if;
  if v_role = 'customer' and exists (select 1 from public.orders where customer_id = v_uid) then
    raise exception 'This account already has customer orders. Use a different account to ride.';
  end if;
  update public.profiles
     set role = 'rider',
         full_name = coalesce(nullif(trim(p_full_name), ''), full_name),
         phone = coalesce(nullif(trim(p_phone), ''), phone),
         vehicle = coalesce(nullif(trim(p_vehicle), ''), vehicle),
         plate_number = coalesce(nullif(trim(p_plate), ''), plate_number)
   where id = v_uid;
end $$;

-- ---------------------------------------------------------------- admin API
create or replace function public.admin_update_order_status(
  p_order uuid, p_status public.order_status, p_note text default null
) returns void language plpgsql security definer set search_path = '' as $$
declare
  v_old public.order_status;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select status into v_old from public.orders where id = p_order for update;
  if not found then raise exception 'Order not found'; end if;
  if v_old = p_status then return; end if;
  if v_old in ('delivered', 'cancelled') then
    raise exception 'Order is already %', replace(v_old::text, '_', ' ');
  end if;
  update public.orders set status = p_status where id = p_order;
  if p_status = 'cancelled' then perform public.restore_order_stock(p_order); end if;
  perform public.log_order_event(p_order, p_status, coalesce(p_note, 'Updated by admin'));
end $$;

create or replace function public.admin_assign_rider(p_order uuid, p_rider uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_name text;
  v_status public.order_status;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select status into v_status from public.orders where id = p_order for update;
  if not found then raise exception 'Order not found'; end if;
  if v_status in ('delivered', 'cancelled') then raise exception 'Order is closed'; end if;
  if p_rider is not null then
    select full_name into v_name from public.profiles
     where id = p_rider and role = 'rider' and rider_approved;
    if not found then raise exception 'Rider is not approved'; end if;
  end if;
  update public.orders set rider_id = p_rider where id = p_order;
  perform public.log_order_event(
    p_order, v_status,
    case when p_rider is null then 'Rider unassigned by admin' else 'Rider ' || v_name || ' assigned by admin' end
  );
end $$;

create or replace function public.admin_set_rider_approval(p_rider uuid, p_approved boolean)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  update public.profiles
     set rider_approved = p_approved,
         rider_online = case when p_approved then rider_online else false end
   where id = p_rider and role = 'rider';
  if not found then raise exception 'Rider not found'; end if;
end $$;

-- ---------------------------------------------------------------- rider API
create or replace function public.rider_accept_order(p_order uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_status public.order_status;
begin
  if not public.is_approved_rider() then raise exception 'Your rider account is not approved yet'; end if;
  update public.orders set rider_id = auth.uid()
   where id = p_order and rider_id is null and status in ('confirmed', 'preparing', 'ready')
  returning status into v_status;
  if not found then raise exception 'This job was already taken'; end if;
  perform public.log_order_event(p_order, v_status, 'Rider accepted the delivery');
end $$;

create or replace function public.rider_release_order(p_order uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_status public.order_status;
begin
  update public.orders set rider_id = null, rider_lat = null, rider_lng = null, rider_location_at = null
   where id = p_order and rider_id = auth.uid() and status in ('confirmed', 'preparing', 'ready')
  returning status into v_status;
  if not found then raise exception 'You can only release a job before pickup'; end if;
  perform public.log_order_event(p_order, v_status, 'Rider released the delivery');
end $$;

create or replace function public.rider_update_status(p_order uuid, p_status public.order_status)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_old public.order_status;
begin
  select status into v_old from public.orders
   where id = p_order and rider_id = auth.uid() for update;
  if not found then raise exception 'This delivery is not assigned to you'; end if;
  if not (
    (p_status = 'out_for_delivery' and v_old in ('confirmed', 'preparing', 'ready'))
    or (p_status = 'delivered' and v_old = 'out_for_delivery')
  ) then
    raise exception 'Cannot move order from % to %', v_old, p_status;
  end if;
  update public.orders set status = p_status where id = p_order;
  perform public.log_order_event(
    p_order, p_status,
    case when p_status = 'delivered' then 'Delivered by rider' else 'Rider picked up the order' end
  );
end $$;

create or replace function public.rider_update_location(p_order uuid, p_lat double precision, p_lng double precision)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if p_lat not between -90 and 90 or p_lng not between -180 and 180 then
    raise exception 'Invalid coordinates';
  end if;
  update public.orders
     set rider_lat = p_lat, rider_lng = p_lng, rider_location_at = now()
   where id = p_order and rider_id = auth.uid()
     and status in ('confirmed', 'preparing', 'ready', 'out_for_delivery');
end $$;

